export type AppErrorCode =
  | "MISSING_FILE"
  | "EMPTY_FILE"
  | "INVALID_FORM_DATA"
  | "FILE_TOO_LARGE"
  | "INVALID_FILE_TYPE"
  | "INVALID_PDF_HEADER"
  | "TOO_MANY_PAGES"
  | "NO_EXTRACTABLE_TEXT"
  | "CORRUPT_PDF"
  | "DOCUMENT_NOT_FOUND"
  | "INVALID_DOCUMENT_ID"
  | "INVALID_REQUEST_BODY"
  | "INVALID_SEARCH_QUERY"
  | "INVALID_TOP_K"
  | "DOCUMENT_WITHOUT_CHUNKS"
  | "EMBEDDING_MODEL_UNAVAILABLE"
  | "EMBEDDING_QUERY_FAILED"
  | "INVALID_ASK_QUESTION"
  | "UNAUTHENTICATED"
  | "RATE_LIMITED"
  | "DOCUMENT_QUOTA_EXCEEDED"
  | "REGISTRATION_FAILED"
  | "OPENROUTER_NOT_CONFIGURED"
  | "RAG_PROVIDER_TIMEOUT"
  | "RAG_PROVIDER_RATE_LIMITED"
  | "RAG_PROVIDER_QUOTA_EXCEEDED"
  | "RAG_PROVIDER_ERROR";

const STATUS_BY_CODE: Record<AppErrorCode, number> = {
  MISSING_FILE: 400,
  EMPTY_FILE: 400,
  INVALID_FORM_DATA: 400,
  FILE_TOO_LARGE: 413,
  INVALID_FILE_TYPE: 415,
  INVALID_PDF_HEADER: 400,
  TOO_MANY_PAGES: 422,
  NO_EXTRACTABLE_TEXT: 422,
  CORRUPT_PDF: 422,
  DOCUMENT_NOT_FOUND: 404,
  INVALID_DOCUMENT_ID: 400,
  INVALID_REQUEST_BODY: 400,
  INVALID_SEARCH_QUERY: 400,
  INVALID_TOP_K: 400,
  DOCUMENT_WITHOUT_CHUNKS: 409,
  EMBEDDING_MODEL_UNAVAILABLE: 503,
  EMBEDDING_QUERY_FAILED: 500,
  INVALID_ASK_QUESTION: 400,
  UNAUTHENTICATED: 401,
  RATE_LIMITED: 429,
  DOCUMENT_QUOTA_EXCEEDED: 429,
  REGISTRATION_FAILED: 400,
  OPENROUTER_NOT_CONFIGURED: 503,
  RAG_PROVIDER_TIMEOUT: 504,
  RAG_PROVIDER_RATE_LIMITED: 429,
  RAG_PROVIDER_QUOTA_EXCEEDED: 503,
  RAG_PROVIDER_ERROR: 502,
};

/**
 * An error whose message is safe to show to the client.
 * Internal details stay in server logs.
 */
export class AppError extends Error {
  readonly code: AppErrorCode;
  readonly status: number;
  readonly retryAfterSeconds: number | null;

  constructor(
    code: AppErrorCode,
    message: string,
    options?: { retryAfterSeconds?: number },
  ) {
    super(message);
    this.name = "AppError";
    this.code = code;
    this.status = STATUS_BY_CODE[code];
    this.retryAfterSeconds = options?.retryAfterSeconds ?? null;
  }
}
